r"""Build a single self-contained comparison file: kb-compare.html

Inlines the Tailwind CSS actually needed by the three variants (_tw.out.css,
generated by the tailwindcss CLI) and the post-React DOM of each variant
(_snapshots.json, captured by _snapshot.py). The result opens by double-click
with no server, no CDN and no network.

Regenerate the inputs first:
    node build.js
    npx tailwindcss@3.4.17 -i _tw.css -o _tw.out.css \
        --content "./_orig.tsx,./_base.tsx,./_senior.tsx" --minify
    python _snapshot.py          # needs the compare/ server on :3002
    python make_standalone.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
# generated inputs and the finished bundle live in the ignored output tree
ART = os.path.join(ROOT, "outputs", "compare")
