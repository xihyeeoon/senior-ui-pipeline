CSS = open(os.path.join(ART, "_tw.out.css"), encoding="utf-8").read()
SNAP = json.load(open(os.path.join(ART, "_snapshots.json"), encoding="utf-8"))

SHELL = open(VIEWER, encoding="utf-8").read()

# The shell's <style> and <header>/<main>/<table> markup are reused verbatim;
# only the frame-loading part differs, so cut the shell at its <script>.
head, _sep, _tail = SHELL.partition("<script>")
head = head.replace('<html lang="ko">', '<html lang="ko">')

JS = """
var CSS = %(css)s;
var SNAP = %(snap)s;
var VARIANTS = [
  {id:'orig',   label:'Original',  sub:'DesignRepair/examples/example1.tsx', tag:''},
  {id:'base',   label:'Base KB',   sub:'outputs/example1_base/property_example1.tsx',
   tag:'<span class="tag w">제안 12 · 규칙 ID 0</span>'},
  {id:'senior', label:'Senior KB', sub:'outputs/example1_seniorkb/property_example1.tsx',
   tag:'<span class="tag g">제안 17 · SDF 인용 12</span>'}
];
var HEIGHT = 1500;
var heights = {};
var width = 1280, fit = true;
var shown = {orig:true, base:true, senior:true};
var grid = document.getElementById('grid');

function doc(id){
  return '<!doctype html><html><head><meta charset="utf-8">' +
         '<style>' + CSS + '</style></head>' +
         '<body style="margin:0"><div id="root">' + SNAP[id] + '</div></body></html>';
}

grid.innerHTML = VARIANTS.map(function(v){
  return '<section class="col" id="col-' + v.id + '">' +
    '<div class="cap"><b>' + v.label + '</b>' + v.tag +
      '<div class="sub">' + v.sub + '</div></div>' +
    '<div class="stage" id="stage-' + v.id + '">' +
      '<iframe id="fr-' + v.id + '" width="' + width + '" height="' + HEIGHT + '"></iframe>' +
    '</div></section>';
}).join('');
VARIANTS.forEach(function(v){ document.getElementById('fr-' + v.id).srcdoc = doc(v.id); });

function measure(v){
  try{
    var d = document.getElementById('fr-' + v.id).contentDocument;
    var root = d && d.getElementById('root');
    var h = root ? Math.ceil(root.getBoundingClientRect().height) : 0;
    if (h > 100) heights[v.id] = h;
  }catch(e){}
}
function layout(){
  var n = VARIANTS.filter(function(v){ return shown[v.id]; }).length || 1;
  grid.style.gridTemplateColumns = 'repeat(' + n + ', minmax(0,1fr))';
  VARIANTS.forEach(function(v){
    var col = document.getElementById('col-' + v.id);
    col.classList.toggle('hidden', !shown[v.id]);
    if (!shown[v.id]) return;
    var fr = document.getElementById('fr-' + v.id);
    var stage = document.getElementById('stage-' + v.id);
    fr.width = width;
    fr.height = heights[v.id] || HEIGHT;
    measure(v);
    fr.height = heights[v.id] || HEIGHT;
    var avail = col.clientWidth;
    var scale = fit ? Math.min(1, avail / width) : 1;
    fr.style.transform = 'scale(' + scale + ')';
    stage.style.height = ((heights[v.id] || HEIGHT) * scale) + 'px';
    stage.style.overflowX = (scale === 1 && width > avail) ? 'auto' : 'hidden';
  });
}
[200, 600, 1500].forEach(function(t){ setTimeout(layout, t); });
function group(sel, fn){
  var els = document.querySelectorAll(sel);
  Array.prototype.forEach.call(els, function(b){
    b.onclick = function(){ fn(b, els); layout(); };
  });
}
group('[data-w]', function(b, els){
  width = +b.dataset.w;
  Array.prototype.forEach.call(els, function(o){ o.setAttribute('aria-pressed', o === b); });
});
group('[data-fit]', function(b, els){
  fit = b.dataset.fit === '1';
  Array.prototype.forEach.call(els, function(o){ o.setAttribute('aria-pressed', o === b); });
});
group('[data-col]', function(b){
  var id = b.dataset.col;
  shown[id] = !shown[id];
  b.setAttribute('aria-pressed', shown[id]);
});
addEventListener('resize', layout);
addEventListener('load', layout);
layout();
""" % {"css": json.dumps(CSS), "snap": json.dumps(SNAP, ensure_ascii=False)}

